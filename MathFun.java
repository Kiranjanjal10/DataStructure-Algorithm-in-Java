public class MathFun {
    public static void main(String[] args) {
        System.out.println(Math.abs(-4.7));
        System.out.println(Math.acos(0.64));
        System.out.println(Math.addExact(12, 16));
        System.out.println(Math.asin(0.64));
        System.out.println(Math.atan(0.5));
        System.out.println(Math.atan2(0.4, 0.6));
        System.out.println(Math.cbrt(27));
        System.out.println(Math.cbrt(27));
        System.out.println(Math.pow(2, 8));
        System.out.println(Math.min(2.0, 0.25));
        System.out.println(Math.max(2.0, 0.25));
        System.out.println(Math.sqrt(9));
    }
}
